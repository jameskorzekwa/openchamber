#!/usr/bin/env node
// Deterministic scheduling through systemd user units. A daily timer runs
// `reconcile.mjs tick`; each admitted worker gets a one-shot deadline timer
// that runs `reconcile.mjs deadline` for exactly its session. No model, agent
// or credential is involved in scheduling.
// Install only after deployment approval.
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const UNIT = 'j2k-upstream-recovery';
export const ON_CALENDAR = '*-*-* 08:00:00 UTC';
export const USER_UNIT_DIRECTORY = '/home/jkorzekwa/.config/systemd/user';
// Used only when a tick admits a worker for actionable recovery.
export const DEFAULT_MODEL = { providerID: 'claude-agent', id: 'opus' };
const MARKER = '# Generated by tools/upstream-recovery/schedule.mjs; regenerate instead of editing.';
// Existing bee2 service roots (`/etc/bee2/opencode.env`). The units carry
// paths only; credentials stay in Secret Service and the GitHub CLI store.
const SERVICE_ENVIRONMENT = {
  HOME: '/srv/opencode-data/jkorzekwa/opencode/home',
  XDG_CONFIG_HOME: '/srv/opencode-data/jkorzekwa/opencode/config',
  XDG_DATA_HOME: '/srv/opencode-data/jkorzekwa/opencode/xdg',
  XDG_STATE_HOME: '/srv/opencode-data/jkorzekwa/opencode/state',
  XDG_CACHE_HOME: '/srv/opencode-data/jkorzekwa/opencode/cache',
  TMPDIR: '/srv/opencode-data/jkorzekwa/opencode/tmp',
  DBUS_SESSION_BUS_ADDRESS: 'unix:path=/run/user/1000/bus',
};
// systemd expands `%`, `$`, quotes and whitespace in unit values. Paths outside
// this set are rejected instead of escaped.
const UNIT_SAFE = /^\/[A-Za-z0-9._/@+-]+$/;
const SESSION_ID = /^ses_[0-9a-f]{32}$/;

const run = (binary, args) => execFileSync(binary, args, {
  encoding: 'utf8', timeout: 30_000, stdio: ['ignore', 'pipe', 'pipe'],
}).trim();
const userSystemctl = (args) => run('systemctl', ['--user', ...args]);

export function configuration(file) {
  const config = JSON.parse(readFileSync(file, 'utf8'));
  config.model ??= DEFAULT_MODEL;
  if (!isAbsolute(config.stateDirectory || '') || !config.model.providerID || !config.model.id) {
    throw new Error('Config requires absolute stateDirectory and model {providerID,id}');
  }
  return config;
}

function reconcilerService(description, args, node, extra) {
  const script = fileURLToPath(new URL('./reconcile.mjs', import.meta.url));
  for (const path of [args[1], node, script]) {
    if (!UNIT_SAFE.test(path)) throw new Error(`Unit path must be absolute and contain only [A-Za-z0-9._/@+-]: ${path}`);
  }
  const environment = { ...SERVICE_ENVIRONMENT, PATH: `${dirname(node)}:/home/jkorzekwa/.local/bin:/usr/bin:/bin` };
  return `${MARKER}
[Unit]
Description=${description}
ConditionPathIsMountPoint=/srv/opencode-data
RequiresMountsFor=/srv/opencode-data/jkorzekwa
${extra.unit}
[Service]
Type=oneshot
${Object.entries(environment).map(([name, value]) => `Environment=${name}=${value}`).join('\n')}
WorkingDirectory=${SERVICE_ENVIRONMENT.HOME}
ExecStart=${node} ${script} ${args.join(' ')}
# The wrapper bounds its locked child (tick 10 min; deadline 13 min with lock wait).
TimeoutStartSec=15min
UMask=0077
LimitCORE=0
${extra.service}`;
}

export function renderUnits(configFile, node = process.execPath) {
  const service = reconcilerService('J2K upstream recovery reconciler (deterministic; starts a worker only for actionable recovery)',
    ['tick', configFile], node, { unit: '', service: '' });
  const timer = `${MARKER}
[Unit]
Description=Daily 08:00 UTC J2K upstream recovery check

[Timer]
OnCalendar=${ON_CALENDAR}
AccuracySec=1min
# A tick missed while bee2 was down runs once at the next boot.
Persistent=true
Unit=${UNIT}.service

[Install]
WantedBy=timers.target
`;
  return { [`${UNIT}.service`]: service, [`${UNIT}.timer`]: timer };
}

export const deadlineUnit = (sessionID) => `${UNIT}-deadline-${sessionID}`;
export const deadlineCalendar = (deadlineAt) => `${new Date(Math.ceil(deadlineAt / 1000) * 1000).toISOString().slice(0, 19).replace('T', ' ')} UTC`;

// One worker attempt's time budget. The timer is a unit file, not a transient
// `systemd-run` timer, so it survives a reboot; `Persistent=true` starts the
// service at boot when the deadline passed while bee2 was down.
export function renderDeadlineUnits(configFile, sessionID, deadlineAt, node = process.execPath) {
  if (!SESSION_ID.test(sessionID) || !Number.isSafeInteger(deadlineAt)) throw new Error('Deadline requires a generated session ID and integer deadline');
  const name = deadlineUnit(sessionID);
  const service = reconcilerService(`J2K upstream recovery deadline for ${sessionID}`,
    ['deadline', configFile, sessionID, `${deadlineAt}`], node, {
      // Bounded retry when OpenCode or the lock is unavailable: 4 starts.
      unit: 'StartLimitIntervalSec=2h\nStartLimitBurst=4\n',
      service: 'Restart=on-failure\nRestartSec=5min\n',
    });
  const timer = `${MARKER}
[Unit]
Description=J2K upstream recovery deadline for ${sessionID}

[Timer]
OnCalendar=${deadlineCalendar(deadlineAt)}
AccuracySec=1s
Persistent=true
Unit=${name}.service

[Install]
WantedBy=timers.target
`;
  return { [`${name}.service`]: service, [`${name}.timer`]: timer };
}

// Real systemd checks against rendered units, without touching the user
// manager or its unit directory. `verify` exits 0 after ignoring an unknown
// key or unparsable value, so any diagnostic output is a failure.
export function verifyUnits(units, calendar = ON_CALENDAR) {
  const directory = mkdtempSync(join(tmpdir(), 'recovery-units-'));
  try {
    const files = Object.entries(units).map(([name, text]) => {
      writeFileSync(join(directory, name), text, { mode: 0o600 });
      return join(directory, name);
    });
    const check = spawnSync('systemd-analyze', ['--user', '--man=no', 'verify', ...files], {
      encoding: 'utf8', timeout: 30_000,
      // A private runtime directory lets user-scope verification run without
      // a user manager session (CI, SSH without lingering).
      env: { ...process.env, XDG_RUNTIME_DIR: directory },
    });
    const diagnostics = `${check.stdout || ''}${check.stderr || ''}`.trim();
    if (check.error || check.status !== 0 || diagnostics) {
      throw new Error(`systemd-analyze verify rejected the units: ${check.error?.code || diagnostics || `status ${check.status}`}`);
    }
    return { verified: Object.keys(units), calendar: run('systemd-analyze', ['calendar', '--iterations=2', calendar]) };
  } finally { rmSync(directory, { recursive: true, force: true }); }
}

// Refuses to replace a file this tool did not generate. Returns the names
// that changed; identical units are left untouched.
export function writeUnits(units, directory = USER_UNIT_DIRECTORY) {
  const pending = Object.entries(units).filter(([name, text]) => {
    const target = join(directory, name);
    if (!existsSync(target)) return true;
    const current = readFileSync(target, 'utf8');
    if (!current.startsWith(MARKER)) throw new Error(`${target} exists and was not generated by schedule.mjs; refusing to overwrite`);
    return current !== text;
  });
  mkdirSync(directory, { recursive: true, mode: 0o700 });
  for (const [name, text] of pending) {
    const temporary = join(directory, `.${name}.${process.pid}.tmp`);
    writeFileSync(temporary, text, { mode: 0o600 });
    renameSync(temporary, join(directory, name));
  }
  return pending.map(([name]) => name);
}

const showUnit = (systemctl, unit, properties) => Object.fromEntries(systemctl(['show', unit, '-p', properties.join(',')])
  .split('\n').filter(Boolean).map((line) => [line.slice(0, line.indexOf('=')), line.slice(line.indexOf('=') + 1)]));

// Runs before prompt admission. Any failure throws, so no prompt is sent
// without an enabled deadline. Re-registering the same attempt writes the same
// deadline: a retried admission never extends it.
export function registerDeadline(configFile, job, { directory = USER_UNIT_DIRECTORY, systemctl = userSystemctl } = {}) {
  const units = renderDeadlineUnits(configFile, job.sessionID, job.deadlineAt);
  verifyUnits(units, deadlineCalendar(job.deadlineAt));
  writeUnits(units, directory);
  const timer = `${deadlineUnit(job.sessionID)}.timer`;
  systemctl(['daemon-reload']);
  systemctl(['enable', '--now', timer]);
  const state = showUnit(systemctl, timer, ['ActiveState', 'UnitFileState']);
  if (state.ActiveState !== 'active' || state.UnitFileState !== 'enabled') {
    throw new Error(`Deadline timer ${timer} is not active and enabled`);
  }
}

// Removes one session's deadline units after enforcement found it inactive.
// Idempotent: a retry after the files are gone only reloads the manager.
export function releaseDeadline(sessionID, { directory = USER_UNIT_DIRECTORY, systemctl = userSystemctl } = {}) {
  if (!SESSION_ID.test(sessionID)) throw new Error('Invalid session ID');
  const name = deadlineUnit(sessionID);
  if (!existsSync(join(directory, `${name}.timer`))) { systemctl(['daemon-reload']); return; }
  systemctl(['disable', '--now', `${name}.timer`]);
  // Persistent=true keeps a stamp file; systemd.timer(5) says to clean it
  // before uninstalling.
  systemctl(['clean', '--what=state', `${name}.timer`]);
  // The timer file goes last: its presence marks an unfinished release.
  for (const file of [`${name}.service`, `${name}.timer`]) {
    const target = join(directory, file);
    if (existsSync(target) && readFileSync(target, 'utf8').startsWith(MARKER)) rmSync(target);
  }
  systemctl(['daemon-reload']);
}

function status() {
  return {
    timer: showUnit(userSystemctl, `${UNIT}.timer`, ['LoadState', 'UnitFileState', 'ActiveState', 'NextElapseUSecRealtime', 'LastTriggerUSec']),
    service: showUnit(userSystemctl, `${UNIT}.service`, ['LoadState', 'ActiveState', 'Result', 'ExecMainStatus', 'ExecMainExitTimestamp']),
    deadlines: userSystemctl(['list-units', '--all', '--plain', '--no-legend', `${UNIT}-deadline-*`]).split('\n').filter(Boolean),
  };
}

async function main() {
  const [mode, configFile] = process.argv.slice(2);
  if (!['preview', 'verify', 'install', 'status', 'disable'].includes(mode) || !configFile) {
    throw new Error('Usage: node schedule.mjs preview|verify|install|status|disable <absolute-config.json>');
  }
  configuration(configFile);
  const units = renderUnits(configFile);
  if (mode === 'preview') {
    for (const [name, text] of Object.entries(units)) console.log(`# ${join(USER_UNIT_DIRECTORY, name)}\n${text}`);
    return;
  }
  if (mode === 'verify') {
    // Deadline units are rendered per attempt; check their shape too.
    const sample = Date.now() + 2 * 60 * 60_000;
    verifyUnits(renderDeadlineUnits(configFile, `ses_${'0'.repeat(32)}`, sample), deadlineCalendar(sample));
    console.log(JSON.stringify(verifyUnits(units), null, 2));
    return;
  }
  if (mode === 'install') {
    // The timers execute this checkout's reconciler. Pin it to a committed
    // source so the recorded commit is what runs.
    const source = dirname(fileURLToPath(import.meta.url));
    if (run('git', ['-C', source, 'status', '--porcelain', '--', '.'])) throw new Error(`${source} has uncommitted changes; install from a clean reviewed checkout`);
    const commit = run('git', ['-C', source, 'rev-parse', 'HEAD']);
    verifyUnits(units);
    const changed = writeUnits(units);
    userSystemctl(['daemon-reload']);
    userSystemctl(['enable', '--now', `${UNIT}.timer`]);
    console.log(JSON.stringify({ commit, changed, ...status() }, null, 2));
    return;
  }
  // Disabling stops future ticks only: unit files, state, running workers and
  // their deadline timers remain.
  if (mode === 'disable') userSystemctl(['disable', '--now', `${UNIT}.timer`]);
  console.log(JSON.stringify(status(), null, 2));
}

if (resolve(process.argv[1] || '') === fileURLToPath(import.meta.url)) {
  main().catch((error) => { console.error(error.message); process.exitCode = 1; });
}
